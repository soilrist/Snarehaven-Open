# (슬롯, 8 꼭짓점) — 꼭짓점 순서: 아래 네 점(x0y0·x1y0·x1y1·x0y1) 다음 위 네 점 같은 순서
def _hexa(mesh, slot, corners):
    """여섯 면 덩어리 — 면마다 새 정점·새 묶음(각진 모양). 바깥 방향은 덩어리 중심에서 면 중심 쪽."""
    center = [sum(c[k] for c in corners) / 8.0 for k in range(3)]
    for face in ((0, 1, 2, 3), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)):
        mesh.group += 1
        pts = [corners[i] for i in face]
        mid = [sum(p[k] for p in pts) / 4.0 for k in range(3)]
        out = tuple(mid[k] - center[k] for k in range(3))
        a, b, c, d = (mesh.v(*p) for p in pts)
        mesh.tri(slot, a, b, c, out)
        mesh.tri(slot, a, c, d, out)


def _box(mesh, slot, x0, x1, y0, y1, z0, z1, top_inset=0.0):
    """축 맞춘 상자. top_inset 만큼 윗면 y 폭을 좁혀 윗모서리를 깎는다(슬라이드)."""
    bottom = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)]
    top = [(x0, y0 + top_inset, z1), (x1, y0 + top_inset, z1), (x1, y1 - top_inset, z1), (x0, y1 - top_inset, z1)]
    _hexa(mesh, slot, bottom + top)


def _tube_x(mesh, slot, cap_slot, x0, x1, z, radius, sides=8, y=0.0):
    """X 축 원통(총구 통) — 옆면은 한 묶음(둥글게), 앞 끝 마개는 cap_slot(총구 구멍 색)."""
    def ring(x):
        return [mesh.v(x, y + radius * math.cos(math.tau * i / sides), z + radius * math.sin(math.tau * i / sides))
                for i in range(sides)]
    back, front = ring(x0), ring(x1)
    mesh.group += 1
    for i in range(sides):
        j = (i + 1) % sides
        mid = (0.0, math.cos(math.tau * (i + 0.5) / sides), math.sin(math.tau * (i + 0.5) / sides))
        mesh.tri(slot, back[i], back[j], front[j], mid)
        mesh.tri(slot, back[i], front[j], front[i], mid)
    for rim, x, cap, sign in ((back, x0, slot, -1.0), (front, x1, cap_slot, 1.0)):
        mesh.group += 1
        tip = mesh.v(x, y, z)
        for i in range(sides):
            mesh.tri(cap, rim[i], rim[(i + 1) % sides], tip, (sign, 0.0, 0.0))


